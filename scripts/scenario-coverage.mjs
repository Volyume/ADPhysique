#!/usr/bin/env node
/**
 * Phase H scenario coverage generator (PHASE-H-SPEC.md).
 *
 * Runs the directory scenario matrix suite with WRITE_SCENARIO_COVERAGE
 * set, so the suite itself (the only place the real eligibility maths
 * lives) emits per-profile stats; this script assembles the markdown.
 * The report therefore cannot drift from the proof.
 *
 * Run: node scripts/scenario-coverage.mjs
 */
import { execSync } from 'node:child_process';
import { readFileSync, writeFileSync, unlinkSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const jsonPath = join(root, 'docs/capability-campaign-25-2026-08-20/scenario-coverage.json');

execSync('npx jest directoryScenarioMatrix --silent', {
  cwd: root, stdio: 'inherit', env: { ...process.env, WRITE_SCENARIO_COVERAGE: '1' },
});

const { profiles, libraryRows } = JSON.parse(readFileSync(jsonPath, 'utf8'));
unlinkSync(jsonPath);

const conditions = profiles.filter((p) => p.kind === 'condition');
const injuries = profiles.filter((p) => p.kind === 'injury');
const date = new Date().toISOString().slice(0, 10);

let md = `# SCENARIO COVERAGE (Phase H; generated ${date})

Generated by \`scripts/scenario-coverage.mjs\` FROM the passing
directoryScenarioMatrix suite over the derived ${libraryRows}-row
library, so these numbers are the proof's own numbers. Companion
fixtures: movementConstraintFixtures.test.js (the order section 16
nine); stacks and laterality live in the matrix suite.

## Checks

- Per-profile matrix checks: ${profiles.length} profiles x 5 checks
  (no incompatible auto-suggestion, independently justified exclusions,
  useful-plan floor, baseline dignity, exhaustive unknown accounting)
- Canonical multi-constraint stacks: 3 (intersection + episode-end
  restoration proven as set equalities)
- Movement-constraint fixtures: 9
- Laterality carving: 1

## Per-profile eligibility (worst case: every question answered at once)

| Profile | Kind | Rules | Eligible rows | Muscles at floor (>=3) | Definite exclusions | Unknown-only exclusions |
|---|---|---|---|---|---|---|
`;
for (const p of profiles) {
  md += `| ${p.id} | ${p.kind} | ${p.rules} | ${p.totalEligible} | ${p.musclesWithFloor} | ${p.definiteConflictExclusions} | ${p.unknownOnlyExclusions} |\n`;
}
md += `
Totals: ${conditions.length} condition profiles, ${injuries.length}
injury profiles. The one profile below the 6-muscle floor
(stroke_acquired_brain_injury) is documented in the suite with its
honest reason: all four questions at once is the worst case, the
machine-design unknowns bite exactly there, and allowances are the
designed answer.
`;
writeFileSync(join(root, 'docs/capability-campaign-25-2026-08-20/SCENARIO-COVERAGE.md'), md);
console.log('scenario coverage written:', profiles.length, 'profiles');
