#!/usr/bin/env node
/**
 * CC27 demand-ontology coverage report (ARCHITECTURE section 8.3/8.5;
 * ROADMAP CC27 "coverage report artefact").
 *
 * Reads the structured exercise corpus (src/lib/exerciseCorpus/), runs the
 * pure derivation in
 * src/lib/capability/demands.js over every canonical exercise, and writes
 * docs/capability-campaign-25-2026-08-20/CC27-DEMAND-COVERAGE.md with
 * per-axis and per-muscle coverage, the section 33.3 priority muscles
 * called out, contradiction-check results, and the NULL worklist per axis
 * (the curation working surface).
 *
 * Deterministic; reads only repo files; writes only the report.
 * Run: node scripts/demand-coverage-report.mjs
 */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const demands = await import(join(root, 'src/lib/capability/demands.js'));
const { deriveDemandMetadata, validateDemandMetadata, DEMAND_FIELDS } = demands;

// EL-14 (exercise-library-expansion-2026-09-05): re-anchored onto the
// structured corpus instead of parsing seedExercises.js's RAW text — RAW
// no longer exists (the format migration replaced it). Retired stub
// entries are already excluded from CORPUS.
const { CORPUS } = await import(join(root, 'src/lib/exerciseCorpus/index.js'));
const rows = CORPUS.map((entry) => ({
  name: entry.name,
  primaryMuscle: entry.primaryMuscle,
  secondaryMuscles: entry.secondaryMuscles ?? [],
  equipment: entry.equipment,
  movementPattern: entry.movementPattern,
  compoundIsolation: entry.compound ? 'compound' : 'isolation',
}));

// Subregion tagging (for family-tag context on the priority muscles) is
// now a per-entry field, not a separate name-keyed map.
const taggedNames = new Set(CORPUS.filter((e) => e.subregion != null).map((e) => e.name));

// ── Derive ──────────────────────────────────────────────────────────────
const derived = rows.map((ex) => ({ ex, meta: deriveDemandMetadata(ex), errs: [] }));
for (const d of derived) d.errs = validateDemandMetadata(d.meta);

const total = rows.length;
const muscles = [...new Set(rows.map((r) => r.primaryMuscle))].sort();
const familyThin = muscles.filter((m) => !rows.some((r) => r.primaryMuscle === m && taggedNames.has(r.name)));

const pct = (n, d) => (d ? `${Math.round((n / d) * 100)}%` : '-');
const covered = (list, f) => list.filter((d) => d.meta[f] !== null && d.meta[f] !== undefined).length;

let md = `# CC27 DEMAND-ONTOLOGY COVERAGE REPORT

Generated by \`scripts/demand-coverage-report.mjs\` over the exercise
corpus (${total} canonical exercises). NULL = UNKNOWN by design (CAP-8):
this report is the curation working surface, not a defect list. Axis
coverage floors pinned in \`capabilityDemands.test.js\`.

## Per-axis coverage (non-NULL over ${total})

| Axis | Known | Coverage |
|---|---|---|
`;
for (const f of DEMAND_FIELDS) {
  md += `| ${f} | ${covered(derived, f)} | ${pct(covered(derived, f), total)} |\n`;
}

md += `\n## Per-muscle coverage (family-thin muscles marked *, section 33.3 priority)\n\n| Muscle | Rows | position | grip | overhead | floor | bilat.upper | bilat.lower | balance | axial |\n|---|---|---|---|---|---|---|---|---|---|\n`;
for (const m of muscles) {
  const list = derived.filter((d) => d.ex.primaryMuscle === m);
  const mark = familyThin.includes(m) ? ' *' : '';
  md += `| ${m}${mark} | ${list.length} | ${pct(covered(list, 'position'), list.length)} | ${pct(covered(list, 'gripDemand'), list.length)} | ${pct(covered(list, 'overheadPosition'), list.length)} | ${pct(covered(list, 'floorAccess'), list.length)} | ${pct(covered(list, 'bilateralUpper'), list.length)} | ${pct(covered(list, 'bilateralLower'), list.length)} | ${pct(covered(list, 'balanceDemand'), list.length)} | ${pct(covered(list, 'axialLoad'), list.length)} |\n`;
}

const bad = derived.filter((d) => d.errs.length);
md += `\n## Contradiction check (section 8.5)\n\n${bad.length === 0 ? 'None. Every derived set passes validateDemandMetadata.' : bad.map((d) => `- ${d.ex.name}: ${d.errs.join(', ')}`).join('\n')}\n`;

md += `\n## Family-thin muscles (section 33.3): ${familyThin.join(', ')}\n\nDemand-axis coverage carries these muscles (family rules are OFFERED only\nwhere families exist); their per-axis coverage is in the table above.\n`;

md += `\n## NULL worklist per axis (curation surface)\n`;
for (const f of DEMAND_FIELDS) {
  const nulls = derived.filter((d) => d.meta[f] === null || d.meta[f] === undefined);
  md += `\n### ${f} (${nulls.length} unknown)\n\n`;
  md += nulls.length ? nulls.map((d) => `${d.ex.name} [${d.ex.primaryMuscle}/${d.ex.equipment}]`).join('; ') : '(none)';
  md += '\n';
}

writeFileSync(join(root, 'docs/capability-campaign-25-2026-08-20/CC27-DEMAND-COVERAGE.md'), md);
console.log(`rows=${total} contradictions=${bad.length}`);
for (const f of DEMAND_FIELDS) console.log(`${f}: ${pct(covered(derived, f), total)}`);
