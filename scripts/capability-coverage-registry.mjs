#!/usr/bin/env node
/**
 * CC28 coverage-registry tooling (Amendment deliverables 1-3; ROADMAP
 * "coverage measurement tooling feeding the registry").
 *
 * Measures, from the repo's own seed + derivation (no live data):
 *  - per capability profile: compatible exercise counts per muscle;
 *  - per routine family: ship status against its own profile;
 * and writes docs/capability-campaign-25-2026-08-20/
 * CAPABILITY-COVERAGE-REGISTRY.md. Marketing claims stay all-NO until
 * their own gates pass (Amendment section 27) - this registry measures
 * CONTENT coverage, it never asserts readiness.
 *
 * Run: node scripts/capability-coverage-registry.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const { deriveDemandMetadata } = await import(join(root, 'src/lib/capability/demands.js'));

const seedSrc = readFileSync(join(root, 'src/lib/seedExercises.js'), 'utf8');
const start = seedSrc.indexOf('const RAW = [');
const body = seedSrc.slice(start, seedSrc.indexOf('\n];', start));
const rows = [];
const re = /\[\s*'([^']+)',\s*'([a-z_]+)',\s*\[([^\]]*)\],\s*'([a-z_]+)',\s*'([a-z_]+)',\s*(true|false),\s*(\d+),\s*(\d+),\s*(\d+),\s*(\d+)\s*\]/g;
let m;
while ((m = re.exec(body)) !== null) {
  const base = { name: m[1], primaryMuscle: m[2], equipment: m[4], movementPattern: m[5], compoundIsolation: m[6] === 'true' ? 'compound' : 'isolation' };
  rows.push({ ...base, d: deriveDemandMetadata(base) });
}

// Profile predicates mirror the resolver's demandAxisConflict === false.
const PROFILES = {
  'Seated / cannot stand': (r) => ['seated', 'lying', 'kneeling'].includes(r.d.position),
  'No floor access': (r) => r.d.floorAccess === false,
  'One arm (bilateral upper constrained)': (r) => r.d.bilateralUpper === false || (r.d.bilateralUpper == null && r.d.unilateralLoadable === true),
  'One leg (bilateral lower constrained)': (r) => r.d.bilateralLower === false || (r.d.bilateralLower == null && r.d.unilateralLoadable === true),
  'Grip-limited (no firm bar grip)': (r) => ['none', 'supportive'].includes(r.d.gripDemand),
  'No overhead work': (r) => r.d.overheadPosition === false,
  'No spinal loading': (r) => r.d.axialLoad === false,
  'No impact': (r) => r.d.impact === false,
  'Balance-supported only': (r) => r.d.balanceDemand === 'supported',
};

const MUSCLES = [...new Set(rows.map((r) => r.primaryMuscle))].sort();

const FAMILIES = [
  ['Seated Full Body', 'SHIPPED v1 (beginner)'],
  ['Seated Upper Strength', 'SHIPPED v1 (intermediate)'],
  ['No-Floor Full Body', 'SHIPPED v1 (beginner)'],
  ['Supported Machine Builder', 'SHIPPED v1 (beginner)'],
  ['Supported Machine Builder II', 'SHIPPED v1 (intermediate)'],
  ['One-Arm Upper Builder', 'SHIPPED v1 (intermediate)'],
  ['One-Leg Lower Builder', 'SHIPPED v1 (intermediate)'],
  ['Steady-Base Full Body', 'SHIPPED v1 (beginner)'],
  ['Dumbbell & Band Foundations', 'SHIPPED v1 (beginner)'],
  ['No-Overhead Upper Split', 'SHIPPED v1 (intermediate)'],
  ['Grip-Light Machine Circuit', 'SHIPPED v1 (beginner; pulling gap stated in-plan)'],
  ['Grip-limited PULLING collection', 'NOT SHIPPED - deferred to DEF-3 (implement guidance): the only grip-light pulling in the library is extension-class work, below any honest coverage threshold. Registry keeps this row until it ships.'],
];

let md = `# CAPABILITY COVERAGE REGISTRY

Generated by \`scripts/capability-coverage-registry.mjs\` from the seed
library (${rows.length} exercises) and the demand derivation. CONTENT
coverage only; marketing readiness stays governed by the Amendment
section 27 matrix (all NO until each gate passes). Family plan
compatibility is separately proven by construction in
\`capabilityFamilyPlans.test.js\`.

## Compatible exercises per capability profile

| Profile | Total | ${MUSCLES.join(' | ')} |
|---|---|${MUSCLES.map(() => '---').join('|')}|
`;
for (const [label, pred] of Object.entries(PROFILES)) {
  const hit = rows.filter(pred);
  const per = {};
  for (const r of hit) per[r.primaryMuscle] = (per[r.primaryMuscle] ?? 0) + 1;
  md += `| ${label} | ${hit.length} | ${MUSCLES.map((mu) => per[mu] ?? 0).join(' | ')} |\n`;
}

md += `\n## Routine family ship status (Amendment sections 15-17)\n\n| Family | Status |\n|---|---|\n`;
for (const [name, status] of FAMILIES) md += `| ${name} | ${status} |\n`;

md += `\nUnknown-rate note: profiles count DEFINITE compatibility only; NULL
axes are excluded on both sides (CAP-8), so every number here is a floor,
not an estimate.\n`;

writeFileSync(join(root, 'docs/capability-campaign-25-2026-08-20/CAPABILITY-COVERAGE-REGISTRY.md'), md);
console.log('registry written;', rows.length, 'rows,', Object.keys(PROFILES).length, 'profiles');
