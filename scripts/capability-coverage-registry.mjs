#!/usr/bin/env node
/**
 * CC28 coverage-registry tooling (Amendment deliverables 1-3; ROADMAP
 * "coverage measurement tooling feeding the registry").
 *
 * Measures, from the repo's own seed + derivation (no live data):
 *  - per capability profile: compatible exercise counts per muscle;
 *  - per routine family: ship status against its own profile;
 * and writes docs/capability-campaign-25-2026-08-20/
 * CAPABILITY-COVERAGE-REGISTRY.md. Marketing claims stay all-NO until
 * their own gates pass (Amendment section 27) - this registry measures
 * CONTENT coverage, it never asserts readiness.
 *
 * Run: node scripts/capability-coverage-registry.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const { deriveDemandMetadata } = await import(join(root, 'src/lib/capability/demands.js'));

const seedSrc = readFileSync(join(root, 'src/lib/seedExercises.js'), 'utf8');
const start = seedSrc.indexOf('const RAW = [');
const body = seedSrc.slice(start, seedSrc.indexOf('\n];', start));
const rows = [];
const re = /\[\s*'([^']+)',\s*'([a-z_]+)',\s*\[([^\]]*)\],\s*'([a-z_]+)',\s*'([a-z_]+)',\s*(true|false),\s*(\d+),\s*(\d+),\s*(\d+),\s*(\d+)\s*\]/g;
let m;
while ((m = re.exec(body)) !== null) {
  const base = { name: m[1], primaryMuscle: m[2], equipment: m[4], movementPattern: m[5], compoundIsolation: m[6] === 'true' ? 'compound' : 'isolation' };
  rows.push({ ...base, d: deriveDemandMetadata(base) });
}

// Profile predicates mirror the resolver's demandAxisConflict === false.
const PROFILES = {
  'Seated / cannot stand': (r) => ['seated', 'lying', 'kneeling'].includes(r.d.position),
  'No floor access': (r) => r.d.floorAccess === false,
  'One arm (bilateral upper constrained)': (r) => r.d.bilateralUpper === false || (r.d.bilateralUpper == null && r.d.unilateralLoadable === true),
  'One leg (bilateral lower constrained)': (r) => r.d.bilateralLower === false || (r.d.bilateralLower == null && r.d.unilateralLoadable === true),
  'Grip-limited (no firm bar grip)': (r) => ['none', 'supportive'].includes(r.d.gripDemand),
  'No overhead work': (r) => r.d.overheadPosition === false,
  'No spinal loading': (r) => r.d.axialLoad === false,
  'No impact': (r) => r.d.impact === false,
  'Balance-supported only': (r) => r.d.balanceDemand === 'supported',
  'No weight through hands/wrists': (r) => r.d.weightBearingHands === false,
};

const MUSCLES = [...new Set(rows.map((r) => r.primaryMuscle))].sort();

const FAMILIES = [
  ['Seated Full Body', 'SHIPPED v1 (beginner)'],
  ['Seated Upper Strength', 'SHIPPED v1 (intermediate)'],
  ['No-Floor Full Body', 'SHIPPED v1 (beginner)'],
  ['Supported Machine Builder', 'SHIPPED v1 (beginner)'],
  ['Supported Machine Builder II', 'SHIPPED v1 (intermediate)'],
  ['One-Arm Upper Builder', 'SHIPPED v1 (intermediate)'],
  ['One-Leg Lower Builder', 'SHIPPED v1 (intermediate)'],
  ['Steady-Base Full Body', 'SHIPPED v1 (beginner)'],
  ['Dumbbell & Band Foundations', 'SHIPPED v1 (beginner)'],
  ['No-Overhead Upper Split', 'SHIPPED v1 (intermediate)'],
  ['Grip-Light Machine Circuit', 'SHIPPED v1 (beginner; pulling gap stated in-plan)'],
  ['Grip-limited PULLING collection', 'RESOLVED BY MECHANISM, not by a plan (GC-D7): a strap-assisted pulling PLAN would be incompatible by construction (honest bar-grip metadata), so the shipped answer is per-exercise strap/cuff setup guidance (adaptedSetup: pulldown, row, pull-up, deadlift, band row), the grip profiles pointing at implements, and the allowance flow re-admitting strapped movements per user. DEF-3 closes on this mechanism set.'],
  ['Seated Home Strength', 'SHIPPED v1 (beginner)'],
  ['Grip-Light Lower Builder', 'SHIPPED v1 (intermediate)'],
  ['Hinge & Hip Lower Builder', 'SHIPPED v1 (intermediate)'],
  ['Seated Upper Strength II', 'SHIPPED v1 (experienced)'],
  ['Steady-Base Strength', 'SHIPPED v1 (experienced)'],
];

let md = `# CAPABILITY COVERAGE REGISTRY

Generated by \`scripts/capability-coverage-registry.mjs\` from the seed
library (${rows.length} exercises) and the demand derivation. CONTENT
coverage only; marketing readiness stays governed by the Amendment
section 27 matrix (all NO until each gate passes). Family plan
compatibility is separately proven by construction in
\`capabilityFamilyPlans.test.js\`.

## Compatible exercises per capability profile

| Profile | Total | ${MUSCLES.join(' | ')} |
|---|---|${MUSCLES.map(() => '---').join('|')}|
`;
for (const [label, pred] of Object.entries(PROFILES)) {
  const hit = rows.filter(pred);
  const per = {};
  for (const r of hit) per[r.primaryMuscle] = (per[r.primaryMuscle] ?? 0) + 1;
  md += `| ${label} | ${hit.length} | ${MUSCLES.map((mu) => per[mu] ?? 0).join(' | ')} |\n`;
}

md += `\n## Routine family ship status (Amendment sections 15-17)\n\n| Family | Status |\n|---|---|\n`;
for (const [name, status] of FAMILIES) md += `| ${name} | ${status} |\n`;

md += `\nUnknown-rate note: profiles count DEFINITE compatibility only; NULL
axes are excluded on both sides (CAP-8), so every number here is a floor,
not an estimate.\n`;

// ── Gap-closure Phase I (order section 26): the directory dimension set,
// generated from the ACTUAL knowledge modules so coverage can never be
// hand-waved. Statuses that are shared mechanisms (coach, check-in,
// reintroduction, learning shield, logging) are stated once - they are
// profile-blind by design (GC-D1/GC-D2).
// The directory modules use bundler-style extensionless imports, so the
// script PARSES them (the same posture as the seed parse above) rather
// than importing.
function parseProfiles(file, kind) {
  const src = readFileSync(join(root, file), 'utf8');
  const blocks = src.split(/\n  \{\n    id: '/).slice(1);
  return blocks.map((b) => {
    const id = b.slice(0, b.indexOf("'"));
    const name = (b.match(/canonicalName: '((?:[^'\\]|\\.)*)'/) ?? [])[1] ?? id;
    // Questions carry ids like sci_q1 in both files (helper calls and
    // inline objects alike), so the id convention is the reliable count.
    const questions = new Set([...b.matchAll(/'(\w+_q\d+)'/g)].map((m) => m[1])).size;
    const evidence = (b.match(/tier: 'T\d'/g) ?? []).length;
    const tiers = [...b.matchAll(/tier: '(T\d)'/g)].map((m) => m[1]).sort();
    const aliasBlock = (b.match(/aliases: \[([^\]]*)\]/) ?? [])[1] ?? '';
    const aliases = (aliasBlock.match(/'/g) ?? []).length / 2;
    const gapsBlock = (b.match(/knownGaps: \[([^\]]*)\]/) ?? [])[1] ?? '';
    const gaps = gapsBlock.trim() ? gapsBlock.replace(/[']/g, '').trim() : 'none recorded';
    return { id, kind, name, questions, evidence, bestTier: tiers[0] ?? 'none', aliases, gaps };
  });
}
const CONDITION_PROFILES = parseProfiles('src/lib/capability/directory/conditions.js', 'condition');
const INJURY_PROFILES = parseProfiles('src/lib/capability/directory/injuries.js', 'injury');

md += `\n## Directory profiles (order section 26 dimensions; generated from the live modules)\n
Shared mechanisms, profile-blind by design: plan generation, builder,
picker, logging, effective prescription, coach, check-in, reintroduction
and the learning shield all consume FUNCTIONAL state only (GC-D1), so
every profile inherits full support the moment its questions are
answered; per-profile automated scenario coverage is the Phase H matrix
suite (every profile iterated by construction). Clinical/expert review,
device validation and user validation remain EXTERNAL and pending for
every profile (founder actions); marketing stays governed by
MARKETING-READINESS-MATRIX.md (all NO).\n
| Profile | Kind | Questions | Evidence (best tier) | Aliases | Known gaps |\n|---|---|---|---|---|---|\n`;
for (const p of [...CONDITION_PROFILES, ...INJURY_PROFILES]) {
  md += `| ${p.name} | ${p.kind} | ${p.questions} | ${p.evidence} (${p.bestTier}) | ${p.aliases} | ${p.gaps} |\n`;
}
md += `\nREAL-DISABLED-USER-VALIDATED: **NO** for every profile (order
section 14 truth field; converts only through CC-F5 rounds).\n`;

writeFileSync(join(root, 'docs/capability-campaign-25-2026-08-20/CAPABILITY-COVERAGE-REGISTRY.md'), md);
console.log('registry written;', rows.length, 'rows,', Object.keys(PROFILES).length, 'profiles,', CONDITION_PROFILES.length + INJURY_PROFILES.length, 'directory profiles');
