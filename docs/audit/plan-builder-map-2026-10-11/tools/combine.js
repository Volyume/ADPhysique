const fs = require('fs');
const S = process.argv[2];
const V = [['3 Oct (older generator, before the rebuild)', 'oct03'], ['9 Oct (new planner, before 10 Oct changes)', 'oct09'], ['Now, 2.13.0 on main', 'now']];
const data = Object.fromEntries(V.map(([, k]) => [k, JSON.parse(fs.readFileSync(`${S}/cmp/${k}.json`, 'utf8'))]));
const ok = (rows) => rows.filter((r) => !r.error);
const pct = (rows, f) => { const o = ok(rows); const c = o.filter(f).length; return `${c} (${Math.round((100 * c) / Math.max(1, o.length))}%)`; };
const avg = (rows, f) => { const o = ok(rows); return (o.reduce((a, r) => a + f(r), 0) / Math.max(1, o.length)).toFixed(1); };
const out = [];
const head = `| Measure | ${V.map(([l]) => l).join(' | ')} |`;
const sep = `|---|${V.map(() => '---').join('|')}|`;
const row = (label, fn) => out.push(`| ${label} | ${V.map(([, k]) => fn(data[k])).join(' | ')} |`);
out.push('## All 1,440 combinations');
out.push('');
out.push(head); out.push(sep);
row('Plans built', (r) => `${ok(r).length} of ${r.length}`);
row('Older generator: exercise names it could not map to a muscle', (r) => (r[0] && r[0].unknownNames !== undefined ? ok(r).reduce((a, x) => a + (x.unknownNames || 0), 0) : 'n/a'));
row("The planner's own readiness check fails", (r) => (ok(r)[0] && ok(r)[0].readinessFail === null ? 'no such check' : pct(r, (x) => x.readinessFail)));
row('Same muscle trained directly in two back-to-back sessions (any gap)', (r) => pct(r, (x) => x.overlapAny));
row('...where that pair is 24 h apart in the usual layout', (r) => pct(r, (x) => x.overlap24));
row('Same exercise in two back-to-back sessions', (r) => pct(r, (x) => x.sameExAdj));
row('Front delts pressed in two back-to-back sessions (any gap)', (r) => pct(r, (x) => x.fdBackToBack));
row('...24 h apart', (r) => pct(r, (x) => x.fdBackToBack24));
row('Overhead press in 2+ sessions', (r) => pct(r, (x) => x.overheadSessions >= 2));
row('A session runs more than 5 min past the chosen length', (r) => pct(r, (x) => x.overLength));
row('A session holds more than 8 exercises or 25 sets', (r) => pct(r, (x) => x.overCeil));
row("A growth muscle below today's category floor (floors set 10 Oct)", (r) => pct(r, (x) => x.belowFloor.length > 0));
row('Average exercises per session', (r) => avg(r, (x) => x.avgExercises));
row('Average sets per exercise (peak week for the new planner)', (r) => avg(r, (x) => x.avgSetsPerExercise));
row('Average total direct sets per week', (r) => avg(r, (x) => x.weeklySets));
out.push('');
for (const goal of ['mens_physique', 'classic_physique', 'bodybuilding', 'bikini', 'wellness', 'figure', 'womens_physique', 'general']) {
  const sub = Object.fromEntries(Object.entries(data).map(([k, rows]) => [k, rows.filter((r) => r.inp.goal === goal)]));
  out.push(`## ${goal} (180 combinations each)`);
  out.push('');
  out.push(head); out.push(sep);
  const r2 = (label, fn) => out.push(`| ${label} | ${V.map(([, k]) => fn(sub[k])).join(' | ')} |`);
  r2("Readiness check fails", (r) => (ok(r)[0] && ok(r)[0].readinessFail === null ? 'no such check' : pct(r, (x) => x.readinessFail)));
  r2('Same muscle directly, back-to-back 24 h apart', (r) => pct(r, (x) => x.overlap24));
  r2('Front delts pressed back-to-back', (r) => pct(r, (x) => x.fdBackToBack));
  r2('Over the chosen length by 5+ min', (r) => pct(r, (x) => x.overLength));
  r2('Over 8 exercises or 25 sets', (r) => pct(r, (x) => x.overCeil));
  r2('Longest session, minutes', (r) => Math.max(...ok(r).map((x) => x.maxMinutes)));
  r2('Lower-body sessions per week, min to max', (r) => { const l = ok(r).map((x) => x.legSessions); return `${Math.min(...l)} to ${Math.max(...l)}`; });
  r2("Below today's category floor", (r) => pct(r, (x) => x.belowFloor.length > 0));
  r2('Average total direct sets per week', (r) => avg(r, (x) => x.weeklySets));
  out.push('');
}
out.push('## Muscles trained directly in back-to-back sessions 24 h apart (plans affected)');
out.push('');
const muscles = ['chest', 'back', 'side_delts', 'rear_delts', 'front_delts', 'biceps', 'triceps', 'quads', 'hamstrings', 'glutes', 'calves', 'abs', 'traps'];
out.push(head.replace('Measure', 'Muscle')); out.push(sep);
for (const m of muscles) row(m, (r) => ok(r).filter((x) => x.overlapMuscles.includes(m)).length);
fs.writeFileSync(`${S}/cmp/table.md`, out.join('\n'));
